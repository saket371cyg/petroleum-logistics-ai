"""
Hill Climbing optimizer for dispatch scheduling.

A "state" is a complete assignment: (tanker, driver, loading_slot).
Neighbors are generated by swapping one element of the assignment at a time
(change tanker, change driver, or change loading slot) among the candidate
pools passed in.

Cost = w1*delivery_time + w2*transport_cost + w3*idle_time + w4*late_penalty + w5*violation_penalty
Fitness = -Cost   (we maximize fitness / minimize cost)

IMPORTANT — this does NOT guarantee a global optimum. Hill climbing can get
stuck at a:
  - local optimum: every neighbor is worse, but a better state exists elsewhere
  - plateau: many neighbors have equal cost, so climbing stalls
  - ridge: improvement requires moving through several equally-costed states
            that a single-swap neighborhood can't reach in one step

Random-restart hill climbing (implemented below) mitigates this by re-running
from several random initial states and keeping the best result found — it
improves the odds of finding a good solution but still does not guarantee
the global optimum.
"""
import random
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from typing import List, Optional, Callable


@dataclass
class DispatchState:
    tanker_id: int
    driver_id: int
    slot_id: int
    slot_start: datetime
    tanker_capacity_l: float


@dataclass
class DispatchCandidatePools:
    tankers: List[dict]     # [{id, capacity_l}]
    drivers: List[dict]     # [{id}]
    slots: List[dict]       # [{id, slot_start}]


@dataclass
class CostBreakdown:
    delivery_time_hours: float
    transport_cost: float
    idle_time_hours: float
    late_penalty: float
    violation_penalty: float
    total_cost: float


WEIGHTS = {
    "delivery_time": 8.0,      # cost per hour of delivery time
    "transport_cost": 1.0,     # direct proportional cost
    "idle_time": 3.0,          # cost per hour tanker sits idle before departure
    "late_penalty": 200.0,     # flat penalty per hour late beyond deadline
    "violation_penalty": 1000.0,  # capacity/eligibility violations
}

COST_PER_KM = 25.0  # INR/km, illustrative


def evaluate_state(
    state: DispatchState,
    order_qty_l: float,
    distance_km: float,
    eta_adjustment_hours: float,
    deadline: datetime,
    now: datetime,
) -> CostBreakdown:
    base_travel_hours = distance_km / 40.0
    delivery_time_hours = base_travel_hours + eta_adjustment_hours

    departure = state.slot_start + timedelta(minutes=30)  # loading buffer
    idle_time_hours = max(0.0, (departure - now).total_seconds() / 3600.0)
    arrival = departure + timedelta(hours=delivery_time_hours)

    late_hours = max(0.0, (arrival - deadline).total_seconds() / 3600.0)
    late_penalty = late_hours * WEIGHTS["late_penalty"]

    violation_penalty = 0.0
    if state.tanker_capacity_l < order_qty_l:
        violation_penalty += WEIGHTS["violation_penalty"]

    transport_cost = distance_km * COST_PER_KM

    total = (
        WEIGHTS["delivery_time"] * delivery_time_hours
        + WEIGHTS["transport_cost"] * transport_cost / 1000.0  # scale to comparable range
        + WEIGHTS["idle_time"] * idle_time_hours
        + late_penalty
        + violation_penalty
    )

    return CostBreakdown(
        delivery_time_hours=round(delivery_time_hours, 2),
        transport_cost=round(transport_cost, 2),
        idle_time_hours=round(idle_time_hours, 2),
        late_penalty=round(late_penalty, 2),
        violation_penalty=round(violation_penalty, 2),
        total_cost=round(total, 2),
    )


def _random_state(pools: DispatchCandidatePools) -> DispatchState:
    t = random.choice(pools.tankers)
    d = random.choice(pools.drivers)
    s = random.choice(pools.slots)
    return DispatchState(tanker_id=t["id"], driver_id=d["id"], slot_id=s["id"],
                          slot_start=s["slot_start"], tanker_capacity_l=t["capacity_l"])


def _neighbors(state: DispatchState, pools: DispatchCandidatePools) -> List[DispatchState]:
    neighbors = []
    for t in pools.tankers:
        if t["id"] != state.tanker_id:
            neighbors.append(DispatchState(tanker_id=t["id"], driver_id=state.driver_id, slot_id=state.slot_id,
                                            slot_start=state.slot_start, tanker_capacity_l=t["capacity_l"]))
    for d in pools.drivers:
        if d["id"] != state.driver_id:
            neighbors.append(DispatchState(tanker_id=state.tanker_id, driver_id=d["id"], slot_id=state.slot_id,
                                            slot_start=state.slot_start, tanker_capacity_l=state.tanker_capacity_l))
    for s in pools.slots:
        if s["id"] != state.slot_id:
            neighbors.append(DispatchState(tanker_id=state.tanker_id, driver_id=state.driver_id, slot_id=s["id"],
                                            slot_start=s["slot_start"], tanker_capacity_l=state.tanker_capacity_l))
    return neighbors


def hill_climb(
    pools: DispatchCandidatePools,
    order_qty_l: float,
    distance_km: float,
    eta_adjustment_hours: float,
    deadline: datetime,
    now: datetime,
    max_iterations: int = 200,
    restarts: int = 5,
):
    """
    Random-restart steepest-ascent hill climbing.
    Returns (best_state, best_cost_breakdown, total_iterations_run).
    """
    if not pools.tankers or not pools.drivers or not pools.slots:
        raise ValueError("No feasible candidates available for optimization.")

    best_state = None
    best_cost = None
    total_iterations = 0

    for _restart in range(restarts):
        current = _random_state(pools)
        current_cost = evaluate_state(current, order_qty_l, distance_km, eta_adjustment_hours, deadline, now)

        for _ in range(max_iterations):
            total_iterations += 1
            neighbors = _neighbors(current, pools)
            if not neighbors:
                break

            scored = [(n, evaluate_state(n, order_qty_l, distance_km, eta_adjustment_hours, deadline, now)) for n in neighbors]
            best_neighbor, best_neighbor_cost = min(scored, key=lambda x: x[1].total_cost)

            if best_neighbor_cost.total_cost < current_cost.total_cost:
                current, current_cost = best_neighbor, best_neighbor_cost
            else:
                # local optimum or plateau reached for this restart
                break

        if best_cost is None or current_cost.total_cost < best_cost.total_cost:
            best_state, best_cost = current, current_cost

    return best_state, best_cost, total_iterations


def benchmark_hill_climb(
    pools: DispatchCandidatePools,
    order_qty_l: float,
    distance_km: float,
    eta_adjustment_hours: float,
    deadline: datetime,
    now: datetime,
    max_iterations: int = 200,
    restarts: int = 5,
) -> dict:
    """Runs the hill-climb optimizer repeatedly and returns a compact benchmark summary."""
    if not pools.tankers or not pools.drivers or not pools.slots:
        raise ValueError("No feasible candidates available for optimization.")

    results = []
    best_total_cost = float("inf")
    best_state = None
    total_iterations = 0

    for restart_index in range(restarts):
        state, cost, iterations = hill_climb(
            pools=pools,
            order_qty_l=order_qty_l,
            distance_km=distance_km,
            eta_adjustment_hours=eta_adjustment_hours,
            deadline=deadline,
            now=now,
            max_iterations=max_iterations,
            restarts=1,
        )
        total_iterations += iterations
        result_entry = {
            "restart": restart_index + 1,
            "state": {
                "tanker_id": state.tanker_id,
                "driver_id": state.driver_id,
                "slot_id": state.slot_id,
            },
            "total_cost": round(cost.total_cost, 2),
            "delivery_time_hours": round(cost.delivery_time_hours, 2),
            "transport_cost": round(cost.transport_cost, 2),
        }
        results.append(result_entry)

        if cost.total_cost < best_total_cost:
            best_total_cost = cost.total_cost
            best_state = state

    average_total_cost = sum(item["total_cost"] for item in results) / max(len(results), 1)
    success_rate = sum(
        1 for item in results if item["total_cost"] <= best_total_cost * 1.05
    ) / max(len(results), 1)

    return {
        "best_total_cost": round(best_total_cost, 2),
        "average_total_cost": round(average_total_cost, 2),
        "restarts": restarts,
        "iterations": total_iterations,
        "success_rate": round(success_rate, 4),
        "best_state": {
            "tanker_id": best_state.tanker_id,
            "driver_id": best_state.driver_id,
            "slot_id": best_state.slot_id,
        } if best_state else None,
        "results": results,
    }
